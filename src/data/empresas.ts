const UNPUBLISHED = "no público";

export function isPublicContact(value?: string): value is string {
  return Boolean(value && value.trim().toLowerCase() !== UNPUBLISHED);
}

export function firstEmail(value: string): string {
  return value.split("/")[0].trim();
}

export function telHref(value: string): string {
  const first = value.split("/")[0].trim();
  const digits = first.replace(/[^\d+]/g, "");
  return `tel:${digits}`;
}

